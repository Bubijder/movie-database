function showSection(idClicked) {
    const allSections = document.querySelectorAll('.mainSection, .secondarySection');
    allSections.forEach((section) => {
        section.style.display = 'none';
    });
    const sectionClicked = document.getElementById(idClicked);
    if (sectionClicked) {
        sectionClicked.style.display = ''; 
    }
}

function sortDatabase(property){
    dataBase.sort((a,b)=>{
        let valA = a[property];
        let valB = b[property];
        if (valA === "0" || valA === "TBA") return 1;
        if (valB === "0" || valB === "TBA") return -1;
        if (typeof valA === 'number') {
            return valB - valA; 
        }
        return valA.toString().localeCompare(valB.toString());
    });
    refreshTable();
}

