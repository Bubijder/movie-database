function generateHTML(dataToRender = dataBase) {
    const tbody = document.querySelector("tbody");
    tbody.innerHTML = '';
    
    dataToRender.forEach((movie) => {
        const originalIndex = dataBase.findIndex(m => m.name === movie.name);
        const genreString = movie.genre.join(", ");
        const newRowString = `
            <tr class="descriptionClick">
                <td onclick="openModal(${originalIndex})">${movie.name}</td>
                <td>${genreString}</td>
                <td>${movie.release_date}</td>
                <td>${movie.rating}</td>
                <td class="personalScore">${movie.score}</td>
            </tr>
        `;
        tbody.insertAdjacentHTML("beforeend", newRowString);
    });
    const description = document.querySelectorAll(".descriptionClick");
    colorRows(description);
}

function openModal(index){
    const movieSelected = dataBase[index];
    
    const modal = document.getElementById('dialogueOpen');
    const movieName = document.getElementById('dialogueTitle');
    const movieRating = document.getElementById('dialogueRating');
    const movieTags = document.getElementById('dialogueTags');
    const movieRezumat = document.getElementById('dialogueRezumat');
    const movieGanduri1 = document.getElementById('dialogueGanduri1');
    const movieGanduri2 = document.getElementById('dialogueGanduri2');
    const movieYesNo = document.getElementById('dialogueVerdict');
    const movieClosingThoughts = document.getElementById('dialogueClosingThoughts');
    const movieScore = document.getElementById('finalScore');

    const showSynopsis = document.querySelector('.subtitluDialog');
    const showVector = document.getElementById('episodeContainer');

    movieName.textContent = movieSelected.name;
    movieRating.textContent = movieSelected.rating;

    movieTags.innerHTML = '';
    movieSelected.genre.forEach((genre) =>{
        const tagElement = document.createElement('span');
        tagElement.textContent = genre;
        tagElement.classList.add('movieTag');
        movieTags.appendChild(tagElement);
    })
    
    if(movieSelected.type === 'movie')
    {
    showSynopsis.style.display = 'block';
    movieRezumat.textContent = movieSelected.synopsis;
    movieRezumat.classList.add('synopsisCSS');

    movieGanduri1.textContent = movieSelected.thoughts1;
    movieGanduri1.classList.add('synopsisCSS');

    movieGanduri2.textContent = movieSelected.thoughts2;
    movieGanduri2.classList.add('synopsisCSS');

    movieYesNo.textContent = movieSelected.verdict;
    if( movieSelected.verdict === 'NO')
        movieYesNo.style.color = "#8B0000";
    else if(movieSelected.verdict === 'YES')
        movieYesNo.style.color = "#006400";
    else  movieYesNo.style.color = "#707e07"

    movieClosingThoughts.textContent = movieSelected.verdictThoughts;
    movieClosingThoughts.classList.add('synopsisCSS');

    movieScore.textContent = movieSelected.score;
    }
    else
    {
        movieRezumat.textContent = '';
        movieGanduri1.textContent = '';
        movieGanduri2.textContent = '';
        showSynopsis.style.display = 'none';
        showVector.innerHTML = '';
        movieSelected.ratingsEpisodes.forEach((rating=>{
            const ratingSquare = document.createElement('div');
            ratingSquare.classList.add('ratingSquare');
            showVector.appendChild(ratingSquare);
        }));

    }
    modal.showModal();
}

