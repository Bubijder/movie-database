function colorRows(description){
    description.forEach((item) =>{
        const rows = item.querySelectorAll(".personalScore");
        rows.forEach((oo) =>{
            if(oo.textContent>8)
                item.style.backgroundColor = "#329D4B";
            else if(oo.textContent>6 && oo.textContent<=8)
                item.style.backgroundColor = "#E4572E";
            else if(oo.textContent === "TBA")
                item.style.backgroundColor = "gray"
            else if(oo.textContent === "0")
                item.style.backgroundColor = "#D9D0DE";
            else
                item.style.backgroundColor = "#C4BB15";
        });
    });
}

